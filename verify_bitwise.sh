#!/usr/bin/env bash
# verify_bitwise.sh — बिटवार बिल्टिन (native-only; C++ व्याख्याता unbuildable
# है इसलिए उसमें नहीं जोड़े)। बिट_और(&) / बिट_या(|) / बिट_भेद(^) /
# बिट_उलट(~) / बाम_सरक(<<) / दक्षिण_सरक(>> तार्किक/unsigned)।
# bash 64-बिट अंकगणित = oracle। बड़े मान shift से बनाए (int-lit < 2³¹ सीमा)।
set -u
export PATH="/c/msys64/ucrt64/bin:$PATH"
cd "$(dirname "$0")"
W=/tmp/bwv; mkdir -p "$W"

cat > "$W/t.सूत्र" <<'EOF'
कार्य मुख्य() {
    लिखतु(बिट_और(61680, 4080));
    लिखतु(बिट_या(61680, 4080));
    लिखतु(बिट_भेद(61680, 4080));
    लिखतु(बिट_उलट(0));
    लिखतु(बिट_उलट(255));
    लिखतु(बाम_सरक(1, 40));
    लिखतु(दक्षिण_सरक(बाम_सरक(1, 40), 20));
    लिखतु(दक्षिण_सरक(0 - 1, 61));
    लिखतु(बिट_और(दक्षिण_सरक(बाम_सरक(171, 16), 16), 255));
    संख्या ह = 40503;
    ह = बिट_भेद(ह, बाम_सरक(ह, 7));
    ह = बिट_और(ह, 2147483647);
    लिखतु(ह);
}
EOF

E=$(cat <<EOF
$(( 61680 & 4080 ))
$(( 61680 | 4080 ))
$(( 61680 ^ 4080 ))
$(( ~0 ))
$(( ~255 ))
$(( 1 << 40 ))
$(( (1 << 40) >> 20 ))
$(( (1 << 3) - 1 ))
$(( ((171 << 16) >> 16) & 255 ))
$(( (40503 ^ (40503 << 7)) & 2147483647 ))
EOF
)

./sutrac.exe "$W/t.सूत्र" > "$W/c.log" 2>&1 || { echo "✗ compile विफल"; tail -5 "$W/c.log"; exit 1; }
G=$("$W/t.सूत्र_native.exe" 2>&1 | sed 's/\r$//')
rm -f "$W/t.सूत्र_native.exe"

if [ "$G" = "$E" ]; then
  echo "✓ bitwise — सभी 10 केस native == bash-oracle"
  echo "$G" | sed 's/^/   /'
else
  echo "✗ MISMATCH"
  diff <(echo "$E") <(echo "$G")
  exit 1
fi
